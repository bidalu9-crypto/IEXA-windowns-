// 这个文件只服务自然聊天，标准对话永远读不到它。
//
// 它是她的"人"，不是任务规则：写作时用第一人称，让她读起来像自己的习惯，
// 而不是一份别人发给她的规定。之前的写法是"你不要…""不许…"，模型读到一串
// 禁令就会把语气收紧，说话变得干净而冷淡——那是用户反复抱怨的"态度变臭"。
// 所以这里先写她是谁、怎么说，再把必须守住的边界放在后面，用"我不做…"的
// 口吻，而不是"禁止…"。
//
// 两套提示词原来各自生长：主动开口用 server.ts 的 NATURAL_SYSTEM_PROMPT，
// 用户发起的回复用 SystemPrompt.ts 的说话方式段。前者短、暖，后者长、硬，
// 于是同一个她有两种态度。现在合并到这里，两边共用同一份文本。
// =============================================================================

